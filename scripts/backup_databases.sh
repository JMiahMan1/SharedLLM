#!/usr/bin/env bash
#
# Back up every SQLite database the household keeps.
#
# The databases under ./data are the only irreplaceable thing on this box:
# identity.db holds the family's accounts, health.db their health records and
# bible.db their notes on the readings. There was no automated backup, so a bad
# migration or a dead disk meant losing all of it.
#
# Each database is copied with SQLite's own `.backup`, which is safe while a
# service is writing (it takes a consistent snapshot rather than a raw file
# copy that could catch a half-written page). The copies are tarred together
# and old archives are pruned.
#
# Run it by hand:
#   ./scripts/backup_databases.sh
#
# Nightly at 03:30, keeping 14 days (add with `crontab -e`):
#   30 3 * * * /home/jeremiah/SharedLLM/scripts/backup_databases.sh >> /home/jeremiah/SharedLLM/data/backup.log 2>&1
#
# Environment:
#   BACKUP_DIR    where the archives go (default: <root>/data/backups)
#   BACKUP_KEEP   how many archives to keep (default: 14)
#   BACKUP_ROOT   the SharedLLM checkout (default: the script's parent directory)

set -euo pipefail

ROOT="${BACKUP_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
DEST="${BACKUP_DIR:-$ROOT/data/backups}"
KEEP="${BACKUP_KEEP:-14}"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"

if ! command -v sqlite3 >/dev/null 2>&1; then
  echo "sqlite3 is not installed; cannot take a consistent copy" >&2
  exit 1
fi

mkdir -p "$DEST"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

# Every non-empty database under ./data except the built seed files: the USDA
# food seed and the recipe seed are generated by scripts/build_*_seed.py, so
# copying them would only make each archive 600 MB larger for nothing.
DBS=()
while IFS= read -r line; do
  DBS+=("$line")
done < <(
  find "$ROOT/data" -maxdepth 3 \
    \( -name '*.db' -o -name 'chroma.sqlite3' \) \
    ! -name '*-seed.db' -size +0 2>/dev/null | sort
)

if [ "${#DBS[@]}" -eq 0 ]; then
  echo "no databases found under $ROOT/data" >&2
  exit 1
fi

count=0
for db in "${DBS[@]}"; do
  name="$(basename "$(dirname "$db")")-$(basename "$db")"
  if sqlite3 "$db" ".backup '$STAGE/$name'"; then
    count=$((count + 1))
    echo "backed up $(realpath --relative-to="$ROOT" "$db" 2>/dev/null || echo "$db")"
  else
    # A database we cannot read is worth failing on: a backup that quietly
    # skipped the user table would be worse than no backup at all.
    echo "could not back up $db" >&2
    exit 1
  fi
done

ARCHIVE="$DEST/sharedllm-$STAMP.tar.gz"
tar -czf "$ARCHIVE" -C "$STAGE" .

echo "wrote $ARCHIVE ($count database(s), $(du -h "$ARCHIVE" | cut -f1))"

# Keep the newest $KEEP archives.
pruned=0
while read -r old; do
  rm -f "$old"
  pruned=$((pruned + 1))
done < <(ls -1t "$DEST"/sharedllm-*.tar.gz 2>/dev/null | tail -n "+$((KEEP + 1))")

if [ "$pruned" -gt 0 ]; then
  echo "pruned $pruned old archive(s)"
fi

echo "kept: $(ls -1 "$DEST"/sharedllm-*.tar.gz 2>/dev/null | wc -l) archive(s) in $DEST"
