#!/usr/bin/env bash
#
# Rotate FERNET_KEY: a new key in .env, every sealed value re-encrypted under it, the old
# key dropped. Run on the server, from the checkout, by a person (the backup asks for a
# passphrase). Docs: docs/KEY_ROTATION.md.
#
#   scripts/rotate_fernet_key.sh preflight   # the dry run: checks everything, changes nothing
#   scripts/rotate_fernet_key.sh backup      # only the encrypted backup of the affected databases
#   scripts/rotate_fernet_key.sh rotate      # backup, new key, restart, re-encrypt, verify
#   scripts/rotate_fernet_key.sh finalize    # verify again, drop the old key, restart, verify
#   scripts/rotate_fernet_key.sh status      # which keys .env and each service hold (fingerprints)
#
# Where FERNET_KEY seals data (each store is re-encrypted inside its own container by
# services/common/fernet_rotation.py):
#   identity           data/identity/identity.db: every *_enc column, encrypted settings, linked
#                      accounts; user.api_key_hash is re-computed (an HMAC keyed with FERNET_KEY)
#   workspace_runtime  its volume's workspace_runtime.db: workspace env and webhook secrets
#   homehub            data/homehub/homehub.db: sealed config entries, refresh-token keys, blobs
#   telemetry          Redis tel:concern-image:* (short-lived, TTL kept)
#
# How the switch stays safe: every service decrypts with FERNET_KEY and then
# FERNET_KEY_PREVIOUS (services/common/fernet_keys.py), so after `rotate` writes the new key
# and moves the old one to FERNET_KEY_PREVIOUS, both open everything while the values are
# re-encrypted. `finalize` refuses to drop the old key until every value opens with the new
# one alone. Every step can be re-run: `rotate` on a half-done rotation resumes it.
#
# .env is read only when a container starts (the owner's rule), so each change to it is
# followed by recreating the services that use the key: identity first (the others ask it
# for config), then workspace_runtime, telemetry and homehub.
#
# No key is ever printed. Keys are generated by scripts/fernet_env.py straight into .env;
# what this script shows are fingerprints (12 hex digits of a key's SHA-256).
#
# The backup (owner's rule: encrypted, never readable without a password) is a tar of
# SQLite-consistent copies of the three databases, encrypted with gpg (AES256, passphrase)
# or, without gpg, age (passphrase). The plain copies exist only in a mode-700 staging
# directory that is removed on every exit. Restore: gpg -d FILE | tar -xf - (docs).
#
# Environment:
#   COMPOSE      the compose command (default: "docker compose"; e.g. "sudo docker compose")
#   ENV_FILE     the .env (default: <checkout>/.env)
#   BACKUP_DIR   where the encrypted backup goes (default: <checkout>/data/backups)
#   WAIT_S       how long to wait for a recreated service (default: 120)
#
# Options: --skip-backup (rotate only; you already have a verified encrypted backup),
#          --allow-undecryptable (accept values no key opens, after looking at the list),
#          --recreate-all (finalize: also recreate every other service so none keeps an old
#          key in its environment).

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ENV_FILE:-$ROOT/.env}"
COMPOSE="${COMPOSE:-docker compose}"
BACKUP_DIR="${BACKUP_DIR:-$ROOT/data/backups}"
WAIT_S="${WAIT_S:-120}"
SERVICES=(identity workspace_runtime telemetry homehub)
SQLITE_SERVICES=(identity workspace_runtime homehub)
FERNET_ENV="$ROOT/scripts/fernet_env.py"

SKIP_BACKUP=0
ALLOW_UNDECRYPTABLE=()
RECREATE_ALL=0
COMMAND="${1:-}"
[ $# -gt 0 ] && shift
for arg in "$@"; do
  case "$arg" in
    --skip-backup) SKIP_BACKUP=1 ;;
    --allow-undecryptable) ALLOW_UNDECRYPTABLE=(--allow-undecryptable) ;;
    --recreate-all) RECREATE_ALL=1 ;;
    *) echo "rotate_fernet_key: unknown option $arg" >&2; exit 2 ;;
  esac
done

die() { echo "rotate_fernet_key: $*" >&2; exit 1; }
say() { echo "== $*"; }

store_of() {
  case "$1" in
    identity) echo identity ;;
    workspace_runtime) echo workspace ;;
    telemetry) echo telemetry ;;
    homehub) echo homehub ;;
    *) die "no store for service $1" ;;
  esac
}

compose() { (cd "$ROOT" && $COMPOSE "$@"); }
rotation() { local svc="$1"; shift; compose exec -T "$svc" python -m services.common.fernet_rotation "$@"; }

# One field of a JSON object on stdin; lists are joined with commas. No eval.
json_field() {
  python3 -c '
import json, sys
value = json.load(sys.stdin).get(sys.argv[1])
if isinstance(value, bool):
    print("true" if value else "false")
elif isinstance(value, list):
    print(",".join(map(str, value)))
elif value is None:
    print("")
else:
    print(value)
' "$1"
}

env_status() { python3 "$FERNET_ENV" status --env "$ENV_FILE"; }

require_tools() {
  command -v python3 >/dev/null || die "python3 is needed"
  command -v docker >/dev/null || die "docker is needed"
  [ -f "$ENV_FILE" ] || die "$ENV_FILE does not exist"
  [ -r "$ENV_FILE" ] && [ -w "$ENV_FILE" ] || die "$ENV_FILE must be readable and writable by $(id -un)"
  compose version >/dev/null 2>&1 || die "'$COMPOSE' does not work here (set COMPOSE, e.g. COMPOSE='sudo docker compose')"
}

require_running() {
  local svc
  for svc in "${SERVICES[@]}"; do
    compose exec -T "$svc" true >/dev/null 2>&1 || die "service $svc is not running; start the stack first"
  done
}

# Does the running service hold the keys .env names? (Fingerprints only.)
check_fingerprints() {
  local svc="$1" want_primary want_previous got got_primary got_previous
  want_primary="$(env_status | json_field fernet_key)"
  want_previous="$(env_status | json_field previous)"
  got="$(rotation "$svc" --store "$(store_of "$svc")" --fingerprint)" || die "$svc could not report its keys"
  got_primary="$(printf '%s' "$got" | json_field primary)"
  got_previous="$(printf '%s' "$got" | json_field previous)"
  if [ "$got_primary" != "$want_primary" ] || [ "$got_previous" != "$want_previous" ]; then
    die "$svc holds keys [$got_primary | ${got_previous:-none}] but .env names [$want_primary | ${want_previous:-none}]: recreate it (it reads .env only at start)"
  fi
  echo "   $svc holds the keys .env names (fingerprint $got_primary${got_previous:+, previous $got_previous})"
}

wait_ready() {
  local svc="$1" waited=0
  until rotation "$svc" --store "$(store_of "$svc")" --fingerprint >/dev/null 2>&1; do
    sleep 3
    waited=$((waited + 3))
    [ "$waited" -lt "$WAIT_S" ] || die "$svc did not come back within ${WAIT_S}s (docker compose logs $svc)"
  done
}

recreate() {
  local svc
  for svc in "${SERVICES[@]}"; do
    say "recreating $svc (it reads .env only at start)"
    compose up -d --no-deps --no-build --force-recreate "$svc"
    wait_ready "$svc"
    check_fingerprints "$svc"
  done
}

run_mode() {
  local mode="$1" svc failed=0
  for svc in "${SERVICES[@]}"; do
    if ! rotation "$svc" --store "$(store_of "$svc")" --mode "$mode" "${ALLOW_UNDECRYPTABLE[@]}"; then
      failed=1
    fi
  done
  return "$failed"
}

read_passphrase() {
  local first second
  [ -r /dev/tty ] || die "the backup passphrase must be typed by a person: run this from a terminal"
  read -rs -p "Backup passphrase (at least 12 characters): " first </dev/tty; echo >/dev/tty
  [ "${#first}" -ge 12 ] || die "the passphrase is too short"
  read -rs -p "Type it again: " second </dev/tty; echo >/dev/tty
  [ "$first" = "$second" ] || die "the two passphrases differ"
  PASSPHRASE="$first"
}

backup() {
  local stamp stage svc out name
  stamp="$(date -u +%Y%m%dT%H%M%SZ)"
  mkdir -p "$BACKUP_DIR" "$ROOT/.tmp"
  umask 077
  stage="$(mktemp -d "$ROOT/.tmp/fernet-backup.XXXXXX")"
  chmod 700 "$stage"
  # shellcheck disable=SC2064
  trap "rm -rf '$stage'" EXIT
  for svc in "${SQLITE_SERVICES[@]}"; do
    name="fernet-rotation-$(store_of "$svc").db"
    rotation "$svc" --store "$(store_of "$svc")" --backup-to "/tmp/$name" >/dev/null \
      || die "could not copy the $svc database"
    compose cp "$svc:/tmp/$name" "$stage/$name" >/dev/null || die "could not fetch the $svc copy"
    compose exec -T "$svc" rm -f "/tmp/$name" || true
    chmod 600 "$stage/$name"
    echo "   copied the $svc database"
  done
  out="$BACKUP_DIR/fernet-rotation-$stamp.tar"
  if command -v gpg >/dev/null 2>&1; then
    out="$out.gpg"
    read_passphrase
    tar -C "$stage" -cf - . | gpg --batch --yes --quiet --pinentry-mode loopback --passphrase-fd 3 \
      --symmetric --cipher-algo AES256 -o "$out" 3< <(printf '%s' "$PASSPHRASE") \
      || die "gpg could not encrypt the backup"
    gpg --batch --quiet --pinentry-mode loopback --passphrase-fd 3 -d "$out" 3< <(printf '%s' "$PASSPHRASE") \
      | tar -tf - >/dev/null || die "the encrypted backup does not decrypt: $out (nothing was changed)"
    PASSPHRASE=""
  elif command -v age >/dev/null 2>&1; then
    out="$out.age"
    echo "   age will ask for the passphrase (twice), then once more to check the backup"
    tar -C "$stage" -cf - . | age -p -o "$out" || die "age could not encrypt the backup"
    age -d "$out" | tar -tf - >/dev/null || die "the encrypted backup does not decrypt: $out (nothing was changed)"
  else
    die "neither gpg nor age is installed: the backup must be encrypted (install gnupg2 or age)"
  fi
  chmod 600 "$out"
  rm -rf "$stage"
  trap - EXIT
  echo "   encrypted backup: $out ($(du -h "$out" | cut -f1)); restore with: gpg -d FILE | tar -xf -  (docs/KEY_ROTATION.md)"
  echo "   note: it is sealed with the OLD key; keep its passphrase apart from the server"
}

preflight() {
  local rotating
  require_tools
  require_running
  say "the .env"
  env_status
  [ "$(env_status | json_field fernet_key_valid)" = "true" ] || die "FERNET_KEY in $ENV_FILE is missing or not a Fernet key"
  [ "$(env_status | json_field readable_by_others)" = "false" ] \
    || echo "   warning: $ENV_FILE is readable by group or others; consider chmod 600" >&2
  rotating="$(env_status | json_field rotating)"
  local svc
  if [ "$rotating" = "true" ]; then
    # A rotation stopped part way: services may still hold the old key until 'rotate' recreates them.
    say "a rotation is in progress; the services' keys (fingerprints):"
    for svc in "${SERVICES[@]}"; do
      printf '   %s: ' "$svc"
      rotation "$svc" --store "$(store_of "$svc")" --fingerprint || die "$svc could not report its keys"
    done
  else
    say "each service holds the keys .env names"
    for svc in "${SERVICES[@]}"; do check_fingerprints "$svc"; done
  fi
  say "every sealed value opens with the keys in use (read only)"
  run_mode plan || die "some values open with no key (listed above). Look at them first; --allow-undecryptable accepts them"
  if command -v gpg >/dev/null 2>&1; then echo "   backups will be encrypted with gpg"
  elif command -v age >/dev/null 2>&1; then echo "   backups will be encrypted with age"
  else die "neither gpg nor age is installed: the backup must be encrypted (install gnupg2 or age)"; fi
  if [ "$rotating" = "true" ]; then
    echo "   a rotation is in progress: 'rotate' resumes it, 'finalize' completes it"
  else
    echo "   ready: 'rotate' would back up ${SQLITE_SERVICES[*]}, write a new key, restart ${SERVICES[*]}, re-encrypt and verify"
  fi
}

rotate() {
  preflight
  if [ "$(env_status | json_field rotating)" != "true" ]; then
    if [ "$SKIP_BACKUP" -eq 1 ]; then
      echo "   --skip-backup: no backup taken now (you said you have a verified encrypted one)" >&2
    else
      say "encrypted backup"
      backup
    fi
    say "new FERNET_KEY in .env (the old one becomes FERNET_KEY_PREVIOUS)"
    python3 "$FERNET_ENV" stage-new --env "$ENV_FILE" >/dev/null
    env_status
  else
    say "resuming the rotation already in progress"
  fi
  recreate
  say "re-encrypting under the new key"
  run_mode apply || die "re-encryption failed (see above); fix it and run 'rotate' again: it resumes"
  say "verifying"
  run_mode verify || die "some values still need the old key; run 'rotate' again"
  cat <<'NEXT'
== done: every value opens with the new key. The old key is still accepted.
   Next (docs/KEY_ROTATION.md):
     1. Reset everyone's sign-in (Admin > Security, or scripts/reset_sign_ins.sh), so extra keys
        and PC agent keys hashed with the old key are re-issued.
     2. scripts/rotate_fernet_key.sh finalize   (drops the old key)
NEXT
}

finalize() {
  require_tools
  require_running
  [ "$(env_status | json_field rotating)" = "true" ] || { echo "no rotation in progress; nothing to finalize"; return 0; }
  local svc
  for svc in "${SERVICES[@]}"; do check_fingerprints "$svc"; done
  say "verifying every value opens with the new key alone"
  run_mode verify || die "not every value opens with the new key yet: run 'rotate' first"
  say "dropping FERNET_KEY_PREVIOUS from .env"
  python3 "$FERNET_ENV" drop-previous --env "$ENV_FILE" >/dev/null
  recreate
  say "verifying with the new key alone"
  run_mode verify || die "a value no longer opens: restore FERNET_KEY_PREVIOUS from the backup notes and run rotate"
  if [ "$RECREATE_ALL" -eq 1 ]; then
    say "recreating every other service so none keeps an old key in its environment"
    compose up -d --no-build --force-recreate
  else
    echo "   other services still hold the old FERNET_KEY in their environment (unused); --recreate-all clears that"
  fi
  echo "== finalized: the old key is gone from .env and from ${SERVICES[*]}"
}

status_cmd() {
  require_tools
  env_status
  local svc
  for svc in "${SERVICES[@]}"; do
    printf '%s: ' "$svc"
    rotation "$svc" --store "$(store_of "$svc")" --fingerprint 2>/dev/null || echo "(not running)"
  done
}

case "$COMMAND" in
  preflight|--dry-run|dry-run) preflight ;;
  backup) require_tools; require_running; backup ;;
  rotate) rotate ;;
  finalize) finalize ;;
  status) status_cmd ;;
  *) sed -n '3,13p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
