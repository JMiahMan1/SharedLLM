"""Upload generated media to the Artifact library.

The gateway produces some media itself (notably Stable Diffusion images in the
agent loop) rather than routing every byte through the execution service. This
helper gives those paths the same durable, quota-checked artifact copy that the
execution generators already create.

Uploads are best-effort: the caller has already generated something useful, so
a storage outage must never turn that into a failed tool call.
"""
import base64
import json
import logging
import os
from typing import Any

from services.common.http import get_client
from services.gateway.config import INTERNAL_SECRET, STORAGE_SVC

log = logging.getLogger("gateway.artifacts")

# Kiosk/voice identities are shared and have no Artifact library or quota.
_NON_PERSONAL_OWNERS = {"", "anonymous", "household"}


def owner_of(user_context: Any) -> str:
    """Extract the Identity username from a UserContext or plain dict."""
    owner = (
        user_context.get("user")
        if isinstance(user_context, dict)
        else getattr(user_context, "user", None)
    )
    return str(owner or "").strip()


def artifact_name(path: str | None, fallback: str) -> str:
    """Use the generated file's basename, never a path from the caller."""
    name = os.path.basename((path or "").replace("\\", "/")).strip()
    return (name or fallback)[:255]


async def create_artifact(
    *,
    user_context: Any,
    kind: str,
    name: str,
    data: bytes,
    mime_type: str | None = None,
    workspace_id: str | None = None,
    generator: str | None = None,
    metadata: dict | None = None,
    timeout: int = 120,
) -> dict | None:
    """POST generated bytes to storage and return the artifact, or ``None``."""
    owner = owner_of(user_context)
    if owner in _NON_PERSONAL_OWNERS:
        log.debug("Skipping artifact for non-personal identity %r", owner)
        return None
    if not data:
        log.warning("Skipping empty artifact %r", name)
        return None

    payload = {
        "name": artifact_name(name, "artifact"),
        "kind": kind,
        "mime_type": mime_type,
        "workspace_id": workspace_id,
        "generator": generator,
        "metadata": metadata or {},
        "content_b64": base64.b64encode(data).decode("ascii"),
    }
    try:
        async with get_client().post(
            f"{STORAGE_SVC}/artifacts",
            json=payload,
            headers={"X-Internal-Secret": INTERNAL_SECRET, "X-User": owner},
            timeout=timeout,
        ) as resp:
            body = await resp.text()
            if resp.status not in (200, 201):
                log.warning(
                    "Artifact upload rejected for %s (status %s): %s",
                    name,
                    resp.status,
                    body[:300],
                )
                return None
            try:
                return json.loads(body or "{}")
            except (TypeError, ValueError):
                log.warning("Artifact upload returned an unreadable body for %s", name)
                return None
    except Exception as e:
        log.warning("Artifact upload failed for %s: %s", name, e)
        return None
