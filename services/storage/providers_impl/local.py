"""A local-disk storage provider for artifacts.

Artifacts are addressed by an opaque id generated by the service; the caller
never supplies a path. ``_path`` still refuses anything that is not a single,
plain filename so a corrupted database row cannot escape the artifacts root.
"""
from __future__ import annotations

import asyncio
import os
from pathlib import Path
from typing import Any

from services.storage.models import StorageEntry
from services.storage.providers import StorageProvider


class LocalStorageProvider(StorageProvider):
    def __init__(self, root: str | Path):
        self.root = Path(root)

    def _path(self, ref: str) -> Path:
        if not ref or Path(ref).name != ref or ref in {".", ".."}:
            raise ValueError("Invalid artifact storage reference")
        return self.root / ref

    def local_path(self, ref: str) -> Path:
        """The on-disk path, for FileResponse/range streaming."""
        return self._path(ref)

    def write_bytes(self, ref: str, data: bytes, *, verify: bool = True) -> int:
        """Synchronous write used by the metadata layer's transaction path."""
        target = self._path(ref)
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_name(f".{target.name}.tmp")
        tmp.write_bytes(data)
        os.replace(tmp, target)
        if verify and target.stat().st_size != len(data):
            raise OSError("Artifact write verification failed")
        return len(data)

    def delete_file(self, ref: str) -> bool:
        try:
            self._path(ref).unlink()
            return True
        except FileNotFoundError:
            return False

    async def list_entries(self, path: str = "/", recursive: bool = False) -> list[StorageEntry]:
        # Artifact storage is not a browsable document provider; the artifact
        # endpoints own listing. Returning an empty list keeps the provider
        # contract honest instead of pretending the whole library is a folder.
        return []

    async def get_content(self, path: str) -> str | None:
        data = await self.get_bytes(path)
        if data is None:
            return None
        return data.decode("utf-8", errors="replace")

    async def get_bytes(self, path: str) -> bytes | None:
        target = self._path(path)

        def _read() -> bytes | None:
            try:
                return target.read_bytes()
            except FileNotFoundError:
                return None

        return await asyncio.to_thread(_read)

    async def write_content(
        self,
        path: str,
        content: str | bytes,
        create_parents: bool = True,
        verify: bool = True,
        is_binary: bool = False,
    ) -> dict[str, Any]:
        target = self._path(path)
        data = content.encode("utf-8") if isinstance(content, str) else content

        def _write() -> None:
            if create_parents:
                target.parent.mkdir(parents=True, exist_ok=True)
            tmp = target.with_name(f".{target.name}.tmp")
            tmp.write_bytes(data)
            os.replace(tmp, target)

        await asyncio.to_thread(_write)
        written = len(data)
        if verify:
            size = await asyncio.to_thread(lambda: target.stat().st_size)
            if size != written:
                raise OSError(f"Artifact write verification failed: wrote {written}, found {size}")
        return {"path": path, "bytes_written": written, "verified": verify}

    async def delete_content(self, path: str) -> bool:
        target = self._path(path)

        def _delete() -> bool:
            try:
                target.unlink()
                return True
            except FileNotFoundError:
                return False

        return await asyncio.to_thread(_delete)
